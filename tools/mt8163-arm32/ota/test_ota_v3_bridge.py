def v3_manifest(assets: dict[str, tuple[bytes, bytes]], boot_sha: str, *,
                board: str = "radar_puffin", slug: str = "radar-puffin",
                channel: str = "stable", tx: str = TX) -> str:
    rows = [("format", "libreecho-ota-v3"), ("manifest_version", "1"),
            ("board", board), ("soc", "mt8163"), ("architecture", "armv7"),
            ("image_profile", "ota"), ("transaction_type", "system"), ("transaction_id", tx),
            ("release", RELEASE), ("version", "0.14.0"),
            ("update_channel", channel), ("service_profile", "production"),
            ("minimum_updater_schema", "3"), ("commit_policy", "after-slot-confirm"),
            ("boot_filename", "boot.img"), ("boot_size", str(BOOT_SIZE)),
            ("boot_sha256", boot_sha), ("feature_ids", ",".join(FEATURES))]
    for feature, daemon in zip(FEATURES, DAEMONS):
        payload, metadata = assets[feature]
        ph, mh = hashlib.sha256(payload).hexdigest(), hashlib.sha256(metadata).hexdigest()
        rows.extend((f"feature_{feature}_{key}", str(value)) for key, value in (
            ("asset", f"libreecho-{slug}-base-{feature}-{ph}.payload.squashfs"),
            ("size", len(payload)), ("sha256", ph),
            ("manifest_asset", f"libreecho-{slug}-base-{feature}-{mh}.manifest.json"),
            ("manifest_size", len(metadata)), ("manifest_sha256", mh),
            ("daemon_path", "usr/local/sbin/" + daemon), ("daemon_sha256", "b" * 64)))
    rows.append(("config_schema", "1"))
    return "".join(f"{key}={value}\n" for key, value in rows)


def control_tar(path: Path, manifest_bytes: bytes, key: SigningKey, boot: bytes,
                signed_bytes: bytes | None = None) -> None:
    signature = key.sign(signed_bytes if signed_bytes is not None else manifest_bytes).signature
    with tarfile.open(path, "w:") as archive:
        for name, data in (("manifest", manifest_bytes),
                           ("manifest.sig", signature.hex().encode() + b"\n"),
                           ("boot.img", boot)):
            info = tarfile.TarInfo(name)
            info.size = len(data)
            info.mode = 0o644
            archive.addfile(info, io.BytesIO(data))


